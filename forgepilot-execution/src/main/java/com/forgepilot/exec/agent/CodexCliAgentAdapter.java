package com.forgepilot.exec.agent;

import com.forgepilot.exec.log.SessionLogStore;
import com.forgepilot.exec.model.InMemoryModelSessionProxy;
import com.forgepilot.exec.model.ModelSessionProxy;
import com.forgepilot.exec.runtime.ProcessRuntime;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import org.springframework.stereotype.Component;

/**
 * Codex CLI 适配器。组装 {@code wire_api = "responses"} 配置，经 {@link ProcessRuntime} 启动。
 * 若本机没有 {@code codex}，抛出 {@link AgentNotAvailableException}，绝不把任务标为完成。
 * <p>
 * Isolation: Agent 环境不得包含控制面 / PostgreSQL / Redis / RabbitMQ / MinIO 管理凭证；
 * 模型长期密钥不进 Agent，只注入会话级代理 URL + 短时令牌。
 */
@Component
public class CodexCliAgentAdapter implements AgentAdapter {

    public static final String INTENDED_ENTRY = "codex";

    public static final AgentCapabilities CAPABILITIES = new AgentCapabilities(
            false, // interactiveInput — Codex MVP 不声明向运行中进程发消息
            false, // nativePause
            true,
            true,
            true,
            true,
            true);

    private final ProcessRuntime processRuntime;
    private final SessionLogStore logStore;
    private final ConcurrentHashMap<String, String> handles = new ConcurrentHashMap<>();

    public CodexCliAgentAdapter(ProcessRuntime processRuntime, SessionLogStore logStore) {
        this.processRuntime = processRuntime;
        this.logStore = logStore;
    }

    @Override
    public AgentKind kind() {
        return AgentKind.CODEX_CLI;
    }

    @Override
    public AgentCapabilities capabilities() {
        return CAPABILITIES;
    }

    @Override
    public AdapterMaturity maturity() {
        return AdapterMaturity.MVP;
    }

    @Override
    public void start(AgentExecutionContext context) {
        if (!processRuntime.isCommandAvailable(INTENDED_ENTRY)) {
            throw new AgentNotAvailableException(
                    "本机未找到 codex CLI（NOT_AVAILABLE）。不会假装编码已完成；请安装 Codex 或使用容器运行时。");
        }
        try {
            Path home = Path.of(context.agentHomePath());
            Files.createDirectories(home);
            Path config = home.resolve("config.toml");
            String toml = """
                    # Generated by ForgePilot. Do not put long-lived provider keys here.
                    model_provider = "forgepilot_proxy"
                    model = "%s"

                    [model_providers.forgepilot_proxy]
                    name = "ForgePilot Session Proxy"
                    base_url = "%s"
                    wire_api = "responses"
                    # auth via env CODEX_API_KEY (session short-lived token only)
                    """.formatted(
                    context.modelId() == null ? "default" : context.modelId(),
                    context.modelProxyBaseUrl());
            Files.writeString(config, toml, StandardCharsets.UTF_8);

            // Prove agent-facing config never includes raw provider apiKey
            String configText = Files.readString(config);
            String lowered = configText.toLowerCase();
            if (lowered.contains("sk-") || lowered.contains("\napi_key") || lowered.contains("api_key=")) {
                throw new IllegalStateException("Codex 配置禁止写入长期 api_key");
            }

            Path log = logStore.logFile(context.sessionId());
            Map<String, String> env = new LinkedHashMap<>();
            env.put("CODEX_HOME", home.toString());
            env.put("CODEX_API_KEY", context.shortLivedModelToken());
            env.put("OPENAI_BASE_URL", context.modelProxyBaseUrl());
            // Explicitly do NOT set OPENAI_API_KEY to a provider secret

            ProcessRuntime.StartedHandle handle = processRuntime.start(new ProcessRuntime.StartSpec(
                    context.sessionId(),
                    List.of(INTENDED_ENTRY, "exec", "--config", config.toString()),
                    Path.of(context.workspacePath()),
                    env,
                    log));
            handles.put(context.sessionId(), handle.handleId());
            logStore.append(context.sessionId(), "codex started pid=" + handle.pid());
        } catch (AgentNotAvailableException ex) {
            throw ex;
        } catch (Exception ex) {
            throw new IllegalStateException("启动 Codex 失败: " + ex.getMessage(), ex);
        }
    }

    /** 供测试/编排检查即将写入的代理配置。 */
    public Map<String, Object> previewAgentConfig(AgentExecutionContext context, ModelSessionProxy proxy) {
        ModelSessionProxy.ModelSessionCredential cred = new ModelSessionProxy.ModelSessionCredential(
                context.sessionId(), "provider", context.modelProxyBaseUrl(), context.shortLivedModelToken());
        if (proxy instanceof InMemoryModelSessionProxy inMemory) {
            return inMemory.agentFacingConfig(cred);
        }
        return Map.of(
                "wire_api", InMemoryModelSessionProxy.WIRE_API,
                "base_url", context.modelProxyBaseUrl(),
                "session_token", context.shortLivedModelToken());
    }

    @Override
    public void sendMessage(String sessionId, String message) {
        throw new UnsupportedOperationException("Codex MVP 不支持向仍在运行的进程发消息；请取消后在同一工作区开新 Session");
    }

    @Override
    public void cancel(String sessionId) {
        String handle = handles.remove(sessionId);
        if (handle != null) {
            processRuntime.destroy(handle);
            logStore.append(sessionId, "codex cancelled");
        }
    }
}
